package Polymorphism;

public class static_polymorphism 
{
	public int add(int a, int b) {  //same method, diff behaviour
		return a+b;
	}
	
	public double add(double a, double d) { //same method, diff behaviour
		return a+d;
	}
	
	public int add(int a, int b, int c) {   //same method, diff behaviour
		return a+b+c;
	}
	
}
